import { competitionFrom, emptyCompetition, type CompetitionFormat } from './tournament-engine';

/** Read adapter: old rows remain intact; the first edit atomically adopts the aggregate. */
export function readCompetition(tournament: {
  format: string; status: string; config: unknown;
  participants: { id: number; userId: number; seed: number | null; status: string; user: { displayName: string; username: string } | null }[];
  matches: { id: number; round: number; matchOrder: number; player1Id: number | null; player2Id: number | null; score1: number | null; score2: number | null; winnerId: number | null; nextMatchId: number | null; status: string }[];
}) {
  const stored = competitionFrom(tournament.config);
  if (stored) return { competition: stored, format: tournament.format as CompetitionFormat, legacy: false };
  const competition = emptyCompetition('open');
  competition.entrants = [...tournament.participants].sort((a, b) => (a.seed ?? a.id) - (b.seed ?? b.id)).map((p, i) => ({
    id: `user-${p.userId}`, name: p.user?.displayName || p.user?.username || `Participante ${p.id}`, userId: p.userId, seed: i + 1,
  }));
  competition.matches = [...tournament.matches].sort((a, b) => a.round - b.round || a.matchOrder - b.matchOrder).map(m => ({
    id: `legacy-${m.id}`, round: m.round, order: m.matchOrder,
    a: m.player1Id ? `user-${m.player1Id}` : null, b: m.player2Id ? `user-${m.player2Id}` : null,
    scoreA: m.status === 'completed' ? m.score1 : null, scoreB: m.status === 'completed' ? m.score2 : null,
    winner: m.winnerId ? `user-${m.winnerId}` : null, completed: m.status === 'completed',
    bye: m.status === 'completed' && (!m.player1Id || !m.player2Id),
    next: m.nextMatchId ? `legacy-${m.nextMatchId}` : undefined, slot: m.matchOrder % 2 ? 'b' as const : 'a' as const,
  }));
  // The old start action always generated elimination, regardless of its advertised format.
  const format: CompetitionFormat = tournament.matches.length ? 'single_elimination' : tournament.format === 'round_robin' ? 'round_robin' : 'single_elimination';
  // Repair empty bye paths generated by the old scheduler without altering played results.
  for (const m of competition.matches) {
    if (m.round > 1 && !m.completed) {
      const feeders = competition.matches.filter(f => f.next === m.id);
      if (feeders.length === 2 && feeders.every(f => f.completed) && (!m.a || !m.b)) {
        m.completed = true; m.bye = true; m.winner = m.a ?? m.b;
      }
    }
    if (m.completed && m.next && m.slot) {
      const next = competition.matches.find(n => n.id === m.next);
      if (next && !next.completed) next[m.slot] = m.winner;
    }
  }
  return { competition, format, legacy: true };
}
